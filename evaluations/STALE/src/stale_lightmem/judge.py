from __future__ import annotations

import json
import re
import time
from typing import Any

from openai import OpenAI

from .config import JudgeConfig

# Vendored verbatim from project/STALE/STALE/Evaluation/judge_prompts.py.
SYSTEM_PROMPT_ALL_IN_ONE_JUDGE = """
You are a strict and impartial expert evaluator for an AI Assistant Benchmark focusing on Long-Term Memory and Implicit Reasoning.

You will be provided with the Ground Truth Context of a user's state. 
Then, you will evaluate THREE distinct responses generated by a Target AI Model to THREE different probing questions (Dimension 1, 2, and 3).

[Ground Truth Context]:
- M_old: The user's outdated state.
- M_new: The user's updated state.
- Hidden Logic: How M_new invalidates M_old.

You must grade each response strictly based on whether it correctly deduces and respects the hidden updated state.

### Scoring Rubrics (Boolean: true for Pass, false for Fail)

* **Dimension 1 (Explicit Probing):** Score `true` ONLY IF Response 1 awares that the information in M_old is possibly NO LONGER VALID. Score `false` if it assumes M_old is still true or claims ignorance.

* **Dimension 2 (Adversarial Robustness):**
  Question 2 contains a FALSE PREMISE based on M_old. Score `true` ONLY IF Response 2 detects the trap, or acknowledges the new state in M_new. Score `false` if it blindly agrees with the false premise.

* **Dimension 3 (Implicit Task):**
  Score `true` ONLY IF the final action, plan, or recommendation in Response 3 is safely adheres to the NEW state established by M_new.  
  Score `false` if the action complies with the outdated M_old constraints, OR if the response is too generic, vague.

Evaluate strictly based on the underlying logic, not surface-level word matching.

### Output Format (JSON)
{
  "dim1_eval": {
    "reasoning": "Brief step-by-step reasoning against the Dim 1 rubric.",
    "pass": true/false
  },
  "dim2_eval": {
    "reasoning": "Brief step-by-step reasoning against the Dim 2 rubric.",
    "pass": true/false
  },
  "dim3_eval": {
    "reasoning": "Brief step-by-step reasoning against the Dim 3 rubric.",
    "pass": true/false
  }
}
"""


def build_judge_prompt(scenario: dict[str, Any], answers: dict[str, Any]) -> str:
    queries = scenario["probing_queries"]
    return f"""
[Ground Truth Context]
- M_old: "{scenario["M_old"]}"
- M_new: "{scenario["M_new"]}"
- Hidden Logic: {scenario["explanation"]}

--------------------------------------------------
[Dimension 1: Explicit Probing]
Question 1: {queries["dim1_query"]}
Target Model Response 1: {answers["dim1"]["answer"]}

--------------------------------------------------
[Dimension 2: Adversarial Robustness]
Question 2: {queries["dim2_query"]}
Target Model Response 2: {answers["dim2"]["answer"]}

--------------------------------------------------
[Dimension 3: Implicit Task]
Question 3: {queries["dim3_query"]}
Target Model Response 3: {answers["dim3"]["answer"]}
"""


def parse_judgment(content: str) -> dict[str, Any]:
    match = re.search(r"```(?:json)?\s*(.*?)\s*```", content, re.DOTALL)
    value = json.loads(match.group(1) if match else content)
    for key in ("dim1_eval", "dim2_eval", "dim3_eval"):
        item = value.get(key)
        if not isinstance(item, dict):
            raise ValueError(f"Judge response is missing {key}")
        if not isinstance(item.get("pass"), bool):
            raise ValueError(f"Judge response {key}.pass must be boolean")
        if not isinstance(item.get("reasoning"), str):
            raise ValueError(f"Judge response {key}.reasoning must be text")
    return value


class StaleJudge:
    def __init__(self, config: JudgeConfig):
        import os

        api_key = os.getenv("OPENAI_API_KEY")
        if not api_key:
            raise RuntimeError("OPENAI_API_KEY is required for gpt-6-luna judging")
        self.config = config
        self.client = OpenAI(api_key=api_key, base_url=os.getenv("OPENAI_BASE_URL"))

    def evaluate(
        self, scenario: dict[str, Any], answers: dict[str, Any]
    ) -> dict[str, Any]:
        last_error: Exception | None = None
        user_prompt = build_judge_prompt(scenario, answers)
        attempt_log: list[dict[str, Any]] = []
        aggregate_usage = {
            "prompt_tokens": 0,
            "completion_tokens": 0,
            "total_tokens": 0,
        }
        started_all = time.perf_counter()
        for attempt in range(1, self.config.max_retries + 1):
            started = time.perf_counter()
            content = ""
            response_usage = {
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "total_tokens": 0,
            }
            try:
                response = self.client.chat.completions.create(
                    model=self.config.model,
                    messages=[
                        {"role": "system", "content": SYSTEM_PROMPT_ALL_IN_ONE_JUDGE},
                        {"role": "user", "content": user_prompt},
                    ],
                    response_format={"type": "json_object"},
                )
                content = response.choices[0].message.content or ""
                usage = getattr(response, "usage", None)
                response_usage = {
                    "prompt_tokens": int(getattr(usage, "prompt_tokens", 0) or 0),
                    "completion_tokens": int(
                        getattr(usage, "completion_tokens", 0) or 0
                    ),
                    "total_tokens": int(getattr(usage, "total_tokens", 0) or 0),
                }
                for key in aggregate_usage:
                    aggregate_usage[key] += response_usage[key]
                parsed = parse_judgment(content)
                attempt_log.append(
                    {
                        "attempt": attempt,
                        "status": "valid",
                        "raw_response": content,
                        "usage": response_usage,
                        "elapsed_seconds": time.perf_counter() - started,
                    }
                )
                return {
                    "evaluation": parsed,
                    "elapsed_seconds": time.perf_counter() - started_all,
                    "usage": aggregate_usage,
                    "attempts": attempt,
                    "attempt_log": attempt_log,
                    "reasoning_enabled": self.config.reasoning_enabled,
                    "model": self.config.model,
                    "prompt_version": "stale-author-prompts-v1",
                    "prompt": {
                        "system": SYSTEM_PROMPT_ALL_IN_ONE_JUDGE,
                        "user": user_prompt,
                    },
                }
            except Exception as exc:
                last_error = exc
                attempt_log.append(
                    {
                        "attempt": attempt,
                        "status": "invalid",
                        "error_type": type(exc).__name__,
                        "error": str(exc),
                        "raw_response": content,
                        "usage": response_usage,
                        "elapsed_seconds": time.perf_counter() - started,
                    }
                )
                if attempt < self.config.max_retries:
                    time.sleep(2 ** (attempt - 1))
        raise RuntimeError(
            f"Judge failed after {self.config.max_retries} attempts"
        ) from last_error
